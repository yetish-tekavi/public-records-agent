"""Run the Milestone 6 evaluation and write results, traces, and generated reports.

    python -m app.evaluation.run                 # both configurations, tag "final"
    python -m app.evaluation.run --tag prefix    # keep a pre-fix measurement separately

Outputs (docs/milestone_6/): evaluation_results_<tag>.json, execution_traces/<tag>/,
and for tag "final": evaluation_results.json, evaluation_results.md, tot_comparison.md,
synthetic_test_cases.json.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import logging
import platform
import sys
from datetime import datetime, timezone
from importlib import metadata

from app.console import prepare_stdout
from app.data_loader import PROJECT_ROOT
from app.evaluation import metrics as m
from app.evaluation.dataset import EXPECTATIONS, load_expectations, materialize
from app.evaluation.harness import CONFIGS, run_all
from app.workflows.state import WorkflowConfig

OUT = PROJECT_ROOT / "docs" / "milestone_6"


def environment() -> dict:
    cfg = WorkflowConfig()
    return {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"), "python": platform.python_version(),
        "platform": f"{platform.system()} {platform.release()}",
        "packages": {p: metadata.version(p) for p in ("langgraph", "chromadb", "presidio-analyzer", "spacy", "en_core_web_md", "mcp", "pydantic")},
        "embedding_model": "all-MiniLM-L6-v2 (ChromaDB default ONNX)", "retrieval": "hybrid (BM25 + semantic), k=4",
        "spacy_model": "en_core_web_md", "transport": "in-process tool executor (same ToolService as the MCP server)",
        "planner": "deterministic rule-based agents (no LLM)", "llm": None,
        "workflow_config": cfg.model_dump(), "configs": CONFIGS,
    }


def compute(scenarios, results) -> dict:
    official = m.official_chunk_ids()
    out = {}
    for name in ("A", "B"):
        rs = [r for r in results if r["config"] == name]
        out[name] = {"detection": m.detection_metrics(scenarios, rs), "recommendations": m.recommendation_metrics(scenarios, rs, official),
                     "workflow": m.workflow_metrics(scenarios, rs)}
    out["tot"] = m.tot_metrics(scenarios, [r for r in results if r["config"] == "B"], [r for r in results if r["config"] == "A"])
    out["tot_baseline_activation"] = m.tot_metrics(scenarios, [r for r in results if r["config"] == "A"], [])["activation"]
    out["safety"] = m.safety_checks(scenarios, results)
    return out


def fmt(r: dict) -> str:
    return "n/a (0 cases)" if r["value"] is None else f"{r['value']:.3f} ({r['numerator']}/{r['denominator']})"


