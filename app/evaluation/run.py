def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Run the Milestone 6 evaluation")
    parser.add_argument("--tag", default="final")
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.WARNING)
    logging.getLogger("presidio-analyzer").setLevel(logging.ERROR)
    prepare_stdout()
    scenarios = materialize()
    env = environment()
    results = asyncio.run(run_all(scenarios))
    metrics = compute(scenarios, results)
    traces = OUT / "execution_traces" / args.tag
    traces.mkdir(parents=True, exist_ok=True)
    for r in results:
        (traces / f"{r['config']}_{r['scenario']}.json").write_text(json.dumps(r, indent=2, ensure_ascii=False), encoding="utf-8")
    payload = {"environment": env, "scenario_count": len(scenarios), "metrics": metrics,
               "runs": [{k: v for k, v in r.items() if k not in ("tool_call_log",)} for r in results]}
    (OUT / f"evaluation_results_{args.tag}.json").write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    if args.tag == "final":
        (OUT / "evaluation_results.json").write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
        (OUT / "synthetic_test_cases.json").write_text(EXPECTATIONS.read_text(encoding="utf-8"), encoding="utf-8")
    write_reports(env, scenarios, results, metrics, args.tag)
    A, B = metrics["A"], metrics["B"]
    print(f"runs: {len(results)}; errors: {sum(1 for r in results if r.get('error'))}")
    for name, blk in (("A", A), ("B", B)):
        print(f"[{name}] precision {fmt(blk['detection']['precision'])} recall {fmt(blk['detection']['recall'])} | action ok {fmt(blk['recommendations']['action_correct'])} "
              f"preferred {fmt(blk['recommendations']['preferred_action'])} grounded {fmt(blk['recommendations']['grounded_citation_accuracy'])} "
              f"unsupported {blk['recommendations']['unsupported_redactions']} | e2e {fmt(blk['workflow']['end_to_end_success'])} "
              f"esc recall {fmt(blk['workflow']['escalation_recall'])} false esc {fmt(blk['workflow']['false_escalation_rate'])}")
        for f in blk["workflow"]["failures"]:
            print(f"     FAIL {f['scenario']}: {'; '.join(f['problems'])}")
    print(f"[ToT] activation {metrics['tot']['activation']} invariants {metrics['tot']['invariant_violations'] or 'ok'}")
    failed_safety = [c["check"] for c in metrics["safety"] if not c["passed"]]
    print(f"[safety] {len(metrics['safety']) - len(failed_safety)}/{len(metrics['safety'])} passed" + (f"; FAILED: {failed_safety}" if failed_safety else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
